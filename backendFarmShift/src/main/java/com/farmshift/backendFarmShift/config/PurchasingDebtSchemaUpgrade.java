package com.farmshift.backendFarmShift.config;

import lombok.RequiredArgsConstructor;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

/**
 * Ensures purchase_payments ledger table exists and backfills baseline payment history
 * for existing purchase invoices with paid_amount > 0.
 */
@Component
@Order(20)
@RequiredArgsConstructor
public class PurchasingDebtSchemaUpgrade implements ApplicationRunner {
    private final JdbcTemplate jdbc;

    @Override
    @Transactional
    public void run(ApplicationArguments args) {
        jdbc.execute("ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS lot_number VARCHAR(100)");
        jdbc.execute("ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS expiry_date DATE");
        jdbc.execute("ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS min_stock NUMERIC(19, 6)");
        jdbc.execute("ALTER TABLE purchase_invoice_items ADD COLUMN IF NOT EXISTS lot_number VARCHAR(100)");
        jdbc.execute("ALTER TABLE purchase_invoice_items ADD COLUMN IF NOT EXISTS expiry_date DATE");

        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS purchase_payments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    invoice_id BIGINT NOT NULL,
                    supplier_id BIGINT NOT NULL,
                    amount BIGINT NOT NULL,
                    payment_date DATE NOT NULL,
                    payment_method VARCHAR(50),
                    cash_fund_id BIGINT,
                    note VARCHAR(500),
                    created_by VARCHAR(150),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_purchase_payments_supplier ON purchase_payments(supplier_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_purchase_payments_invoice ON purchase_payments(invoice_id)");

        jdbc.update("""
                INSERT INTO purchase_payments (invoice_id, supplier_id, amount, payment_date, payment_method, note, created_by)
                SELECT pi.id, pi.supplier_id, pi.paid_amount, pi.invoice_date, 'Tiền mặt',
                       CONCAT('Thanh toán ghi nhận từ hóa đơn ', pi.code), 'Hệ thống'
                FROM purchase_invoices pi
                WHERE pi.paid_amount > 0
                  AND pi.stock_status <> 'Đã hủy'
                  AND NOT EXISTS (
                      SELECT 1 FROM purchase_payments pp WHERE pp.invoice_id = pi.id
                  )
                """);
    }
}
