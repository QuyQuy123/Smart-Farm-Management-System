    private void recomputeFundBalance(CashFund fund) {
        Long txNet = jdbc.queryForObject("""
                SELECT COALESCE(SUM(CASE WHEN type = 'Thu' THEN amount ELSE -amount END), 0)
                FROM cash_transactions
                WHERE fund_id = ?
                """, Long.class, fund.getId());
        Long trIn = jdbc.queryForObject("""
                SELECT COALESCE(SUM(amount), 0)
                FROM cash_fund_transfers
                WHERE to_fund_id = ?
                """, Long.class, fund.getId());
        // Phí chuyển quỹ đã được ghi thành phiếu chi riêng (cash_transactions) nên chỉ trừ amount ở đây.
        Long trOut = jdbc.queryForObject("""
                SELECT COALESCE(SUM(amount), 0)
                FROM cash_fund_transfers
                WHERE from_fund_id = ?
                """, Long.class, fund.getId());
        long computed = (txNet != null ? txNet : 0L) + (trIn != null ? trIn : 0L) - (trOut != null ? trOut : 0L);
        fund.setBalance(computed);
        fundRepository.saveAndFlush(fund);
    }

