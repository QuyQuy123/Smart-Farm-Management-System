    private CycleRef findCycleRefByBarn(String barnName, long fallbackId) {
        List<CycleRef> found = jdbc.query("""
                SELECT c.id, b.name AS barn_name
                FROM farming_cycles c
                JOIN barns b ON b.id = c.barn_id
                WHERE b.name = ?
                ORDER BY c.id ASC
                """, (rs, rowNum) -> {
            long cid = rs.getLong("id");
            return new CycleRef(cid, rs.getString("barn_name"), String.format(Locale.ROOT, "L%06d", cid));
        }, barnName);
        if (!found.isEmpty()) {
            CycleRef ref = found.get(0);
            FarmingCycle entity = new FarmingCycle();
            entity.setId(ref.cycleId());
            return new CycleRef(ref.cycleId(), ref.barnName(), ref.cycleCode(), entity);
        }
        return new CycleRef(null, barnName, String.format(Locale.ROOT, "L%06d", fallbackId), null);
    }

