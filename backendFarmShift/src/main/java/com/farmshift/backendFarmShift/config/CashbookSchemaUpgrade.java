    private CashFund createFund(String name, String accountNo, String bank, String fundType, long balance, String note) {
        CashFund fund = new CashFund();
        fund.setName(name);
        fund.setAccountNo(accountNo);
        fund.setBank(bank);
        fund.setFundType(fundType);
        fund.setBalance(balance);
        fund.setNote(note);
        fund.setActive(true);
        return fundRepository.saveAndFlush(fund);
    }

    private void createTx(String code, LocalDate date, String type, String category, long amount, String contact,
                          String personName, CashFund fund, String note, String creator) {
        CashTransaction tx = new CashTransaction();
        tx.setCode(code);
        tx.setTxDate(date);
        tx.setType(type);
        tx.setCategory(category);
        tx.setAmount(amount);
        tx.setContact(contact);
        tx.setPersonName(personName);
        tx.setFund(fund);
        tx.setNote(note);
        tx.setCreator(creator);
        txRepository.save(tx);
    }

    private void createTransfer(String code, LocalDate date, CashFund from, CashFund to, long amount,
                                String note, String creator) {
        CashFundTransfer tr = new CashFundTransfer();
        tr.setCode(code);
        tr.setTransferDate(date);
        tr.setFromFund(from);
        tr.setToFund(to);
        tr.setAmount(amount);
        tr.setFee(0L);
        tr.setNote(note);
        tr.setCreator(creator);
        transferRepository.save(tr);
    }

    private void createCat(String name, String type, String group, String note) {
        CashTransactionCategory cat = new CashTransactionCategory();
        cat.setName(name);
        cat.setNameKey(type.toLowerCase(Locale.ROOT) + ":" + name.toLowerCase(Locale.ROOT));
        cat.setType(type);
        cat.setCostGroup(group);
        cat.setNote(note);
        cat.setActive(true);
        categoryRepository.save(cat);
    }

    private void createAsset(String code, String name, long cost, int months, String location, LocalDate purchaseDate, String note) {
        FarmAsset asset = new FarmAsset();
        asset.setCode(code);
        asset.setName(name);
        asset.setCost(cost);
        asset.setDepreciationMonths(months);
        asset.setMonthlyDepreciation(Math.round((double) cost / months));
        asset.setBarnLocation(location);
        asset.setPurchaseDate(purchaseDate);
        asset.setStatus("Đang trích khấu hao");
        asset.setNote(note);
        assetRepository.save(asset);
    }

    private void createPayroll(String code, String employeeName, String payPeriod, int days, long rate,
                               long bonus, long advance, long paid, String note) {
        long total = (long) days * rate + bonus;
        long remain = Math.max(0L, total - advance - paid);
        PayrollRecord p = new PayrollRecord();
        p.setCode(code);
        p.setEmployeeName(employeeName);
        p.setPayPeriod(payPeriod);
        p.setWorkDays(days);
        p.setDailyRate(rate);
        p.setBonus(bonus);
        p.setAdvance(advance);
        p.setTotalAmount(total);
        p.setPaidAmount(paid);
        p.setRemainingAmount(remain);
        p.setStatus(remain == 0L ? "Đã thanh toán" : "Còn nợ lương");
        p.setNote(note);
        payrollRepository.save(p);
    }

    private void createCostAllocation(String code, String barnName, String cycleCode, String costType,
                                      long amount, String sourceCode, LocalDate date, String note) {
        CycleCostAllocation c = new CycleCostAllocation();
        c.setCode(code);
        c.setBarnName(barnName);
        c.setCycleCode(cycleCode);
        c.setCostType(costType);
        c.setAmount(amount);
        c.setSourceVoucherCode(sourceCode);
        c.setAllocationDate(date);
        c.setNote(note);
        costAllocationRepository.save(c);
    }
