package com.farmshift.backendFarmShift.config;

import com.farmshift.backendFarmShift.entity.CashFund;
import com.farmshift.backendFarmShift.entity.CashFundTransfer;
import com.farmshift.backendFarmShift.entity.CashTransaction;
import com.farmshift.backendFarmShift.repository.CashFundRepository;
import com.farmshift.backendFarmShift.repository.CashFundTransferRepository;
import com.farmshift.backendFarmShift.repository.CashTransactionRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;

@Component
@Order(30)
@RequiredArgsConstructor
public class CashbookSchemaUpgrade implements ApplicationRunner {
    private final JdbcTemplate jdbc;
    private final CashFundRepository fundRepository;
    private final CashTransactionRepository txRepository;
    private final CashFundTransferRepository transferRepository;

    @Override
    @Transactional
    public void run(ApplicationArguments args) {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS cash_funds (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(150) NOT NULL UNIQUE,
                    account_no VARCHAR(80),
                    bank VARCHAR(150) NOT NULL,
                    fund_type VARCHAR(30) NOT NULL DEFAULT 'BANK',
                    balance BIGINT NOT NULL DEFAULT 0,
                    note VARCHAR(500),
                    active BOOLEAN NOT NULL DEFAULT TRUE,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);

        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS cash_transactions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code VARCHAR(30) NOT NULL UNIQUE,
                    tx_date DATE NOT NULL,
                    type VARCHAR(10) NOT NULL,
                    category VARCHAR(150) NOT NULL,
                    amount BIGINT NOT NULL,
                    contact VARCHAR(100),
                    person_name VARCHAR(200) NOT NULL,
                    fund_id BIGINT NOT NULL,
                    note VARCHAR(1000),
                    creator VARCHAR(150),
                    reference_invoice_code VARCHAR(50),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);

        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS cash_fund_transfers (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code VARCHAR(30) NOT NULL UNIQUE,
                    transfer_date DATE NOT NULL,
                    from_fund_id BIGINT NOT NULL,
                    to_fund_id BIGINT NOT NULL,
                    amount BIGINT NOT NULL,
                    fee BIGINT NOT NULL DEFAULT 0,
                    note VARCHAR(500),
                    creator VARCHAR(150),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);

        if (fundRepository.count() == 0) {
            CashFund mb = createFund("Tài khoản MB Bank (TK Chính)", "0987654321", "Ngân hàng Quân Đội", "BANK", 228920000L,
                    "Tài khoản nhận tiền bán sỉ & thanh toán cám");
            CashFund cash = createFund("Tiền mặt tại quỹ trại", "—", "Quỹ thủ quỹ", "CASH", 53200000L,
                    "Chi trả tiền điện, xăng xe, chi tiêu vặt hàng ngày");
            createFund("Tài khoản Vietcombank dự phòng", "1023456789", "Vietcombank", "BANK", 50000000L,
                    "Quỹ dự phòng rủi ro dịch bệnh");

            if (txRepository.count() == 0) {
                createTx("PT000021", LocalDate.of(2026, 10, 4), "Thu", "Đơn bán gà", 100000000L, "Khách hàng",
                        "Công ty Thực phẩm Sạch Minh Tâm", mb, "Thu tiền bán gà Mía đợt 1", "Admin FarmShift");
                createTx("PC000035", LocalDate.of(2026, 10, 2), "Chi", "Tiền điện & nước trang trại", 8200000L, "Đối tượng khác",
                        "Điện lực Sóc Sơn", mb, "Thanh toán tiền điện tháng 9", "Admin FarmShift");
                createTx("PT000020", LocalDate.of(2026, 9, 28), "Thu", "Đơn bán gà", 191880000L, "Khách hàng",
                        "Trần Văn Tuấn", cash, "Thu trọn tiền bán chuồng J1", "Admin FarmShift");
                createTx("PC000034", LocalDate.of(2026, 9, 25), "Chi", "Thuốc thú y & vắc-xin", 8560000L, "Nhà cung cấp",
                        "Công ty Thuốc Thú y Hanvet", mb, "Chi tiền mua thuốc & vắc-xin", "Admin FarmShift");
                createTx("PC000033", LocalDate.of(2026, 9, 20), "Chi", "Tiền lương công nhân", 18000000L, "Nhân sự",
                        "Lương tổ chăm sóc tháng 9", cash, "Thanh toán lương 2 công nhân", "Admin FarmShift");
            }

            if (transferRepository.count() == 0) {
                createTransfer("CQ000005", LocalDate.of(2026, 10, 1), mb, cash, 20000000L,
                        "Rút tiền mặt chi lương và vật tư tiêu hao", "Nguyễn Văn Hải");
                createTransfer("CQ000004", LocalDate.of(2026, 9, 28), cash, mb, 150000000L,
                        "Nộp tiền mặt bán gà chuồng J1 vào tài khoản", "Nguyễn Văn Hải");
            }
        }
    }

    private CashFund createFund(String name, String accountNo, String bank, String fundType, long balance, String note) {
        CashFund fund = new CashFund();
        fund.setName(name);
        fund.setAccountNo(accountNo);
        fund.setBank(bank);
        fund.setFundType(fundType);
        fund.setBalance(balance);
        fund.setNote(note);
        fund.setActive(true);
        return fundRepository.saveAndFlush(fund);
    }

    private void createTx(String code, LocalDate date, String type, String category, long amount, String contact,
                          String personName, CashFund fund, String note, String creator) {
        CashTransaction tx = new CashTransaction();
        tx.setCode(code);
        tx.setTxDate(date);
        tx.setType(type);
        tx.setCategory(category);
        tx.setAmount(amount);
        tx.setContact(contact);
        tx.setPersonName(personName);
        tx.setFund(fund);
        tx.setNote(note);
        tx.setCreator(creator);
        txRepository.save(tx);
    }

    private void createTransfer(String code, LocalDate date, CashFund from, CashFund to, long amount,
                                String note, String creator) {
        CashFundTransfer tr = new CashFundTransfer();
        tr.setCode(code);
        tr.setTransferDate(date);
        tr.setFromFund(from);
        tr.setToFund(to);
        tr.setAmount(amount);
        tr.setFee(0L);
        tr.setNote(note);
        tr.setCreator(creator);
        transferRepository.save(tr);
    }
}

