    private void seedSingleLegacySale(String id, String code, LocalDate date, String customerCode,
                                      Map<String, Object> flockRow, int qty, BigDecimal weightKg,
                                      BigDecimal unitPrice, BigDecimal totalAmount, BigDecimal paidAmount,
                                      String status, String note) {
        Map<String, Object> customer = jdbc.queryForMap(
                "SELECT id, name, phone, address FROM customer_contacts WHERE code = ?", customerCode);
        long customerId = ((Number) customer.get("id")).longValue();
        long flockId = ((Number) flockRow.get("flock_id")).longValue();
        long barnId = ((Number) flockRow.get("barn_id")).longValue();
        long cycleId = ((Number) flockRow.get("cycle_id")).longValue();
        String flockLabel = flockRow.get("area_name") + " - " + flockRow.get("barn_name")
                + " - " + String.format(Locale.ROOT, "L%06d", cycleId);

        jdbc.update("""
                INSERT INTO flock_movements (flock_id, type, movement_date, quantity, weight_kg, unit_price, note, created_by, created_at)
                VALUES (?, 'HARVEST', ?, ?, ?, ?, ?, 'Trần Kế Toán', CURRENT_TIMESTAMP)
                """, flockId, date, qty, weightKg, unitPrice, "Đơn bán " + code + " - " + note);

        Long movementId = jdbc.queryForObject(
                "SELECT MAX(id) FROM flock_movements WHERE flock_id = ? AND type = 'HARVEST'", Long.class, flockId);

        jdbc.update("UPDATE flocks SET quantity = quantity - ? WHERE id = ? AND quantity >= ?", qty, flockId, qty);
        jdbc.update("UPDATE barns SET current_quantity = current_quantity - ? WHERE id = ? AND current_quantity >= ?", qty, barnId, qty);

        jdbc.update("""
                INSERT INTO sales_orders (id, code, date, customer, phone, address, flock, quantity,
                                          total_weight, unit_price, total_amount, paid_amount, status,
                                          note, customer_id, cycle_id, movement_id, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, CURRENT_TIMESTAMP)
                """, id, code, date, customer.get("name"), customer.get("phone"), customer.get("address"),
                flockLabel, qty, weightKg, unitPrice, totalAmount, paidAmount, status, note,
                customerId, cycleId, movementId);

        jdbc.update("""
                UPDATE customer_contacts
                SET total_bought = COALESCE(total_bought, 0) + ?,
                    debt = COALESCE(debt, 0) + ?
                WHERE id = ?
                """, totalAmount, totalAmount.subtract(paidAmount), customerId);

        jdbc.update("INSERT INTO sales_invoice_numbers VALUES (DEFAULT)");
    }

    private List<PaidPurchaseRow> findPaidPurchases() {
        return jdbc.query("""
                SELECT pi.code, pi.invoice_date, pi.paid_amount, s.name AS supplier_name,
                       pi.flock_id, pi.note
                FROM purchase_invoices pi
                JOIN suppliers s ON s.id = pi.supplier_id
                WHERE pi.paid_amount > 0 AND pi.stock_status <> 'Đã hủy'
                ORDER BY pi.invoice_date ASC, pi.id ASC
                """, (rs, rowNum) -> {
            String code = rs.getString("code");
            boolean isFlock = rs.getObject("flock_id") != null;
            String category;
            if (isFlock || "NH000001".equalsIgnoreCase(code)) {
                category = "Tiền con giống";
            } else if ("NH000000".equalsIgnoreCase(code)) {
                category = "Tiền thức ăn (Cám)";
            } else if ("NH000002".equalsIgnoreCase(code)) {
                category = "Thuốc thú y & vắc-xin";
            } else {
                category = "Thanh toán công nợ NCC";
            }
            String note = rs.getString("note");
            String formattedNote = "Thanh toán hóa đơn " + code + (note != null && !note.isBlank() ? " — " + note : "");
            return new PaidPurchaseRow(
                    code,
                    rs.getObject("invoice_date", LocalDate.class),
                    rs.getLong("paid_amount"),
                    rs.getString("supplier_name"),
                    category,
                    formattedNote
            );
        });
    }

    private List<SalesReceiptRow> findPaidSalesOrders() {
        return jdbc.query("""
                SELECT so.code, so.date, so.paid_amount, so.customer, so.status,
                       COALESCE(cc.payment_method, 'Chuyển khoản') AS payment_method
                FROM sales_orders so
                LEFT JOIN customer_contacts cc ON cc.id = so.customer_id
                WHERE so.paid_amount > 0
                ORDER BY so.date ASC, so.code ASC
                """, (rs, rowNum) -> new SalesReceiptRow(
                rs.getString("code"),
                rs.getObject("date", LocalDate.class),
                rs.getBigDecimal("paid_amount").setScale(0, java.math.RoundingMode.HALF_UP).longValue(),
                rs.getString("customer"),
                rs.getString("status"),
                rs.getString("payment_method")
        ));
    }

