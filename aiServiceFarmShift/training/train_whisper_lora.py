"""Reproducible Whisper LoRA Domain Adaptation Pipeline for Vietnamese Poultry Barn Acoustics.

Targets `vinai/PhoWhisper-medium` or `openai/whisper-large-v3` with PEFT LoRA adapters
using the manifest generated by `prepare_datasets.py` (`whisper_stt_{train,val}.jsonl`).

Supports `--dry-run` for CI/CPU validation without requiring GPU or audio binary files.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import json
from pathlib import Path
from typing import Any

DEFAULT_DATASET_DIR = Path(__file__).resolve().parent / "artifacts" / "datasets"
DEFAULT_OUTPUT_DIR = Path(__file__).resolve().parent / "artifacts" / "whisper_lora"


@dataclass
class WhisperLoraConfig:
    base_model: str = "vinai/PhoWhisper-medium"
    language: str = "vi"
    task: str = "transcribe"
    lora_r: int = 16
    lora_alpha: int = 32
    lora_dropout: float = 0.05
    target_modules: tuple[str, ...] = ("q_proj", "v_proj")
    learning_rate: float = 1e-4
    num_train_epochs: int = 5
    per_device_train_batch_size: int = 8
    sampling_rate: int = 16000
    seed: int = 42


def _resolve_audio_file(audio_path: str, dataset_dir: Path) -> Path:
    p = Path(audio_path)
    if p.is_file():
        return p
    rel_ds = dataset_dir / p
    if rel_ds.is_file():
        return rel_ds
    return Path(__file__).resolve().parents[1] / p


def validate_whisper_manifest(jsonl_path: Path, dataset_dir: Path | None = None) -> dict[str, Any]:
    if not jsonl_path.is_file():
        raise FileNotFoundError(f"Missing Whisper manifest: {jsonl_path}")
    base_dir = dataset_dir or jsonl_path.parent
    count = 0
    existing_audio = 0
    for line_no, raw in enumerate(jsonl_path.read_text(encoding="utf-8").splitlines(), start=1):
        if not raw.strip():
            continue
        row = json.loads(raw)
        if not row.get("normalized_transcript"):
            raise ValueError(f"Line {line_no}: missing normalized_transcript")
        if row.get("audio_path") and _resolve_audio_file(row["audio_path"], base_dir).is_file():
            existing_audio += 1
        count += 1
    if count == 0:
        raise ValueError(f"Empty Whisper manifest: {jsonl_path}")
    return {
        "path": str(jsonl_path),
        "examples": count,
        "existing_audio_files": existing_audio,
    }


def run_whisper_training(
    *,
    dataset_dir: Path,
    output_dir: Path,
    cfg: WhisperLoraConfig,
    dry_run: bool = False,
) -> dict[str, Any]:
    train_stats = validate_whisper_manifest(dataset_dir / "whisper_stt_train.jsonl", dataset_dir)
    val_stats = validate_whisper_manifest(dataset_dir / "whisper_stt_val.jsonl", dataset_dir)

    output_dir.mkdir(parents=True, exist_ok=True)
    plan = {
        "pipeline": "farmshift_whisper_lora",
        "dry_run": dry_run,
        "config": asdict(cfg),
        "train_manifest": train_stats,
        "val_manifest": val_stats,
    }
    (output_dir / "whisper_training_plan.json").write_text(
        json.dumps(plan, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    if dry_run:
        return plan

    if train_stats["existing_audio_files"] == 0:
        raise RuntimeError(
            "No physical .wav/.webm audio files found on disk for Whisper training. "
            "Populate audio files referenced in whisper_stt_train.jsonl or run with --dry-run."
        )

    import torch
    from datasets import Audio, load_dataset
    from peft import LoraConfig, get_peft_model
    from transformers import (
        Seq2SeqTrainer,
        Seq2SeqTrainingArguments,
        WhisperForConditionalGeneration,
        WhisperProcessor,
    )

    torch.manual_seed(cfg.seed)
    processor = WhisperProcessor.from_pretrained(cfg.base_model, language=cfg.language, task=cfg.task)
    model = WhisperForConditionalGeneration.from_pretrained(cfg.base_model)
    model.config.forced_decoder_ids = processor.get_decoder_prompt_ids(language=cfg.language, task=cfg.task)
    peft_cfg = LoraConfig(
        r=cfg.lora_r,
        lora_alpha=cfg.lora_alpha,
        lora_dropout=cfg.lora_dropout,
        target_modules=list(cfg.target_modules),
    )
    model = get_peft_model(model, peft_cfg)

    ds = load_dataset(
        "json",
        data_files={
            "train": str(dataset_dir / "whisper_stt_train.jsonl"),
            "validation": str(dataset_dir / "whisper_stt_val.jsonl"),
        },
    ).cast_column("audio_path", Audio(sampling_rate=cfg.sampling_rate))

    def _prepare(batch):
        audio = batch["audio_path"]
        batch["input_features"] = processor.feature_extractor(
            audio["array"], sampling_rate=audio["sampling_rate"]
        ).input_features[0]
        batch["labels"] = processor.tokenizer(batch["normalized_transcript"]).input_ids
        return batch

    ds = ds.map(_prepare, remove_columns=ds["train"].column_names)

    @dataclass
    class DataCollatorSpeechSeq2SeqWithPadding:
        processor: Any

        def __call__(self, features: list[dict[str, Any]]) -> dict[str, Any]:
            input_features = [{"input_features": f["input_features"]} for f in features]
            batch = self.processor.feature_extractor.pad(input_features, return_tensors="pt")
            label_features = [{"input_ids": f["labels"]} for f in features]
            labels_batch = self.processor.tokenizer.pad(label_features, return_tensors="pt")
            labels = labels_batch["input_ids"].masked_fill(labels_batch.attention_mask.ne(1), -100)
            if (labels[:, 0] == self.processor.tokenizer.bos_token_id).all().cpu().item():
                labels = labels[:, 1:]
            batch["labels"] = labels
            return batch

    args = Seq2SeqTrainingArguments(
        output_dir=str(output_dir),
        learning_rate=cfg.learning_rate,
        num_train_epochs=cfg.num_train_epochs,
        per_device_train_batch_size=cfg.per_device_train_batch_size,
        predict_with_generate=True,
        eval_strategy="epoch",
        save_strategy="epoch",
        seed=cfg.seed,
        report_to="none",
    )
    trainer = Seq2SeqTrainer(
        model=model,
        args=args,
        train_dataset=ds["train"],
        eval_dataset=ds["validation"],
        data_collator=DataCollatorSpeechSeq2SeqWithPadding(processor=processor),
        processing_class=processor.feature_extractor,
    )
    trainer.train()
    model.save_pretrained(str(output_dir / "adapter"))
    return plan


def main() -> int:
    parser = argparse.ArgumentParser(description="FarmShift Whisper LoRA Trainer")
    parser.add_argument("--dataset-dir", type=Path, default=DEFAULT_DATASET_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--base-model", default="vinai/PhoWhisper-medium")
    parser.add_argument("--epochs", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    cfg = WhisperLoraConfig(
        base_model=args.base_model,
        num_train_epochs=args.epochs,
        seed=args.seed,
    )
    result = run_whisper_training(
        dataset_dir=args.dataset_dir,
        output_dir=args.output_dir,
        cfg=cfg,
        dry_run=args.dry_run,
    )
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
